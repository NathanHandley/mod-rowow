-- A character's Ragnarok Online identity (mod-rowow), made on its first entry into the RO world.  Positions use -1 for no map
CREATE TABLE IF NOT EXISTS `mod_rowow_identity` (
	`guid` INT(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT 'Global Unique Identifier',
	`job` SMALLINT(5) UNSIGNED NOT NULL DEFAULT '0' COMMENT 'rAthena job ID',
	`base_level` TINYINT(3) UNSIGNED NOT NULL DEFAULT '1',
	`base_exp` INT(10) UNSIGNED NOT NULL DEFAULT '0',
	`job_level` TINYINT(3) UNSIGNED NOT NULL DEFAULT '1',
	`job_exp` INT(10) UNSIGNED NOT NULL DEFAULT '0',
	`status_points` SMALLINT(5) UNSIGNED NOT NULL DEFAULT '0',
	`skill_points` SMALLINT(5) UNSIGNED NOT NULL DEFAULT '0',
	`str` SMALLINT(5) UNSIGNED NOT NULL DEFAULT '1',
	`agi` SMALLINT(5) UNSIGNED NOT NULL DEFAULT '1',
	`vit` SMALLINT(5) UNSIGNED NOT NULL DEFAULT '1',
	`int` SMALLINT(5) UNSIGNED NOT NULL DEFAULT '1',
	`dex` SMALLINT(5) UNSIGNED NOT NULL DEFAULT '1',
	`luk` SMALLINT(5) UNSIGNED NOT NULL DEFAULT '1',
	`hp` INT(10) UNSIGNED NOT NULL DEFAULT '0',
	`sp` INT(10) UNSIGNED NOT NULL DEFAULT '0',
	`zeny` INT(10) UNSIGNED NOT NULL DEFAULT '0',
	`save_map` INT(10) NOT NULL DEFAULT '-1',
	`save_x` FLOAT NOT NULL DEFAULT '0',
	`save_y` FLOAT NOT NULL DEFAULT '0',
	`save_z` FLOAT NOT NULL DEFAULT '0',
	`save_o` FLOAT NOT NULL DEFAULT '0',
	`last_map` INT(10) NOT NULL DEFAULT '-1' COMMENT 'Where the identity last left the RO world',
	`last_x` FLOAT NOT NULL DEFAULT '0',
	`last_y` FLOAT NOT NULL DEFAULT '0',
	`last_z` FLOAT NOT NULL DEFAULT '0',
	`last_o` FLOAT NOT NULL DEFAULT '0',
	`return_map` INT(10) NOT NULL DEFAULT '-1' COMMENT 'Where the character came into the RO world from',
	`return_x` FLOAT NOT NULL DEFAULT '0',
	`return_y` FLOAT NOT NULL DEFAULT '0',
	`return_z` FLOAT NOT NULL DEFAULT '0',
	`return_o` FLOAT NOT NULL DEFAULT '0',
	`hair_style` TINYINT(3) UNSIGNED NOT NULL DEFAULT '1',
	`hair_color` TINYINT(3) UNSIGNED NOT NULL DEFAULT '0',
	`in_form` TINYINT(3) UNSIGNED NOT NULL DEFAULT '0' COMMENT 'Saved while in the form',
	`updated` INT(10) UNSIGNED NOT NULL DEFAULT '0',
	PRIMARY KEY (`guid`) USING BTREE
);
